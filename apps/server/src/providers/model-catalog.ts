import type { ProviderModelOption as ContractProviderModelOption } from "@nakama/core/contract";

export type ProviderModelOption = ContractProviderModelOption & {
  contextWindow: number;
};

function visionDefault(model: ProviderModelOption): boolean | undefined {
  if (model.provider === "opencode_go" || model.provider === "deepseek") {
    return false;
  }

  if (
    model.provider === "openai" ||
    model.provider === "anthropic" ||
    model.provider === "gemini"
  ) {
    return true;
  }

  return model.supportsVision;
}

function withVisionDefaults(
  models: ProviderModelOption[]
): ProviderModelOption[] {
  return models.map((model) => ({
    ...model,
    supportsVision: visionDefault(model),
  }));
}

